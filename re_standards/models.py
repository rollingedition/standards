"""Open model files a book's examples load: examples/models.toml, read, checked, fetched and pinned.

    [[model]]
    repo = "owner/name"            # a public Hugging Face model
    revision = "<40 hex>"          # a full commit, never a branch
    licence = "apache-2.0"         # one of [models] licences in data/examples.toml
    [model.files]
    "model.safetensors" = { sha256 = "<64 hex>", size = 269060552 }

Every runtime fetches the files once, when it's built, and checks each one's SHA-256 (fetch_models.py). Examples then
run offline with HF_HOME at that cache and HF_HUB_OFFLINE=1, and load each model with the libraries' ordinary call and
its pinned revision, so a reader can copy the code unchanged. `re-check models --pin owner/name` writes the entries:
the commit, the licence and every hash come from Hugging Face, never typed.
"""
from __future__ import annotations

import fnmatch
import hashlib
import json
import re
import tomllib
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path

from . import data_path
from .fetch_models import AGENT, fetch_all, file_url

MODELS = "examples/models.toml"
REPO = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9][A-Za-z0-9._-]*$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")
HEADER = ("# Open models the examples load: fetched once when the runtime is built, checked file by file, then read\n"
          "# offline. Generated by `re-check models --pin`; don't edit by hand.\n")


class ModelsError(ValueError):
    """examples/models.toml is malformed, names a licence we can't ship, or a model can't be pinned."""


def settings() -> dict:
    return tomllib.loads(data_path("examples.toml").read_text(encoding="utf-8"))["models"]


@dataclass(frozen=True)
class File:
    name: str
    sha256: str
    size: int


@dataclass(frozen=True)
class Model:
    repo: str
    revision: str
    licence: str
    files: tuple[File, ...]

    def as_json(self) -> dict:
        return {"repo": self.repo, "revision": self.revision, "licence": self.licence,
                "files": {f.name: {"sha256": f.sha256, "size": f.size} for f in self.files}}


def _file_name(name: str) -> bool:
    parts = name.split("/")
    return bool(name) and "\\" not in name and not name.startswith("/") and all(p not in ("", ".", "..") for p in parts)


def parse(text: str, cfg: dict | None = None) -> list[Model]:
    """The models in a models.toml, or ModelsError naming the first thing wrong."""
    cfg = cfg or settings()
    where = MODELS
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise ModelsError(f"{where} isn't valid TOML: {e}") from None
    if set(data) - {"model"}:
        raise ModelsError(f"{where}: only [[model]] tables belong here, not {', '.join(sorted(set(data) - {'model'}))}")
    allowed = [x.lower() for x in cfg["licences"]]
    models, seen = [], set()
    for i, m in enumerate(data.get("model", []), 1):
        at = f"{where}, model {i}"
        if not isinstance(m, dict):
            raise ModelsError(f"{at}: each model is a [[model]] table")
        extra = set(m) - {"repo", "revision", "licence", "files"}
        if extra:
            raise ModelsError(f"{at}: unknown keys {', '.join(sorted(extra))}")
        repo, revision, licence, files = m.get("repo"), m.get("revision"), m.get("licence"), m.get("files")
        if not isinstance(repo, str) or not REPO.match(repo):
            raise ModelsError(f"{at}: repo must be a Hugging Face model's owner/name, not {repo!r}")
        at = f"{where}, {repo}"
        if repo in seen:
            raise ModelsError(f"{at}: listed twice")
        seen.add(repo)
        if not isinstance(revision, str) or not COMMIT.match(revision):
            raise ModelsError(f"{at}: revision must be a full 40-character commit, never a branch or tag, not {revision!r}")
        if not isinstance(licence, str) or licence.lower() not in allowed:
            raise ModelsError(f"{at}: licence {licence!r} isn't one a book can ship; allowed: {', '.join(allowed)}")
        if not isinstance(files, dict) or not files:
            raise ModelsError(f"{at}: [model.files] must name at least one file")
        pinned = []
        for name, f in sorted(files.items()):
            if not _file_name(name):
                raise ModelsError(f"{at}: {name!r} isn't a file name inside the model's repository")
            if not isinstance(f, dict) or set(f) != {"sha256", "size"}:
                raise ModelsError(f"{at}: {name} needs exactly sha256 and size")
            if not isinstance(f["sha256"], str) or not SHA256.match(f["sha256"]):
                raise ModelsError(f"{at}: {name}'s sha256 must be 64 lowercase hex characters")
            if not isinstance(f["size"], int) or isinstance(f["size"], bool) or f["size"] < 0:
                raise ModelsError(f"{at}: {name}'s size must be a whole number of bytes")
            pinned.append(File(name, f["sha256"], f["size"]))
        models.append(Model(repo, revision, licence.lower(), tuple(pinned)))
    if not models:
        raise ModelsError(f"{where} lists no model: remove the file, or pin one with `re-check models --pin`")
    cap = cfg["max_total_mb"] * 1024 * 1024
    if total_bytes(models) > cap:
        raise ModelsError(f"{where}: the models total {total_bytes(models) / 2**20:,.0f} MB, over the "
                          f"{cfg['max_total_mb']:,} MB a book's runtime may hold")
    return models


def read(book_root: Path) -> list[Model]:
    """The book's models, or [] when it has no models.toml."""
    path = Path(book_root) / MODELS
    return parse(path.read_text(encoding="utf-8")) if path.exists() else []


def total_bytes(models: list[Model]) -> int:
    return sum(f.size for m in models for f in m.files)


def canonical(models: list[Model]) -> str:
    """What a runtime's key covers: the models as data, so a comment or the file's layout can't change it."""
    return json.dumps([m.as_json() for m in models], sort_keys=True, separators=(",", ":"))


def digest(models: list[Model]) -> str:
    return hashlib.sha256(canonical(models).encode()).hexdigest()


def env(cache: Path | str) -> dict[str, str]:
    """What an example's environment adds when its runtime holds models: the cache, and the libraries offline."""
    return {"HF_HOME": str(cache), "HF_HUB_OFFLINE": "1", "HF_HUB_DISABLE_TELEMETRY": "1"}


def fetch(models: list[Model], cache: Path | str, base: str | None = None) -> int:
    return fetch_all([m.as_json() for m in models], cache, base or settings()["base_url"])


# ---------------------------------------------------------------- pinning


def _toml_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)        # a JSON string is a valid TOML basic string


def to_toml(models: list[Model]) -> str:
    out = [HEADER]
    for m in models:
        out += ["[[model]]", f"repo = {_toml_string(m.repo)}", f"revision = {_toml_string(m.revision)}",
                f"licence = {_toml_string(m.licence)}", "", "[model.files]"]
        out += [f"{_toml_string(f.name)} = {{ sha256 = {_toml_string(f.sha256)}, size = {f.size} }}" for f in m.files]
        out.append("")
    return "\n".join(out)


def _get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": AGENT}), timeout=60) as r:
        return r.read()


def _licence(info: dict) -> str:
    card = (info.get("cardData") or {}).get("license")
    if isinstance(card, list):
        card = card[0] if len(card) == 1 else None
    if isinstance(card, str):
        return card.lower()
    tags = [t.split(":", 1)[1] for t in info.get("tags", []) if t.startswith("license:")]
    return tags[0].lower() if len(tags) == 1 else ""


def pin(repo: str, revision: str = "main", files: list[str] | None = None, include: list[str] | None = None,
        base: str | None = None, cfg: dict | None = None) -> Model:
    """A model's entry at `revision`, resolved to its full commit: its licence from its card, and each chosen file's
    SHA-256 and size. Large files carry their SHA-256 in the repository's metadata; small ones are downloaded and
    hashed. `files` names them; otherwise they're the top-level files matching `include` ([models] default_files)."""
    cfg = cfg or settings()
    base = (base or cfg["base_url"]).rstrip("/")
    if not REPO.match(repo):
        raise ModelsError(f"{repo!r} isn't a Hugging Face model's owner/name")
    try:
        info = json.loads(_get(f"{base}/api/models/{repo}/revision/{urllib.parse.quote(revision, safe='')}?blobs=true"))
    except OSError as e:
        raise ModelsError(f"can't read {repo} at {revision} from Hugging Face: {e}") from None
    commit, licence = info.get("sha", ""), _licence(info)
    if not COMMIT.match(commit):
        raise ModelsError(f"Hugging Face gave no commit for {repo} at {revision}")
    if licence not in [x.lower() for x in cfg["licences"]]:
        raise ModelsError(f"{repo}'s licence is {licence or 'not stated'}, which a book can't ship; "
                          f"allowed: {', '.join(cfg['licences'])}")
    siblings = {s["rfilename"]: s for s in info.get("siblings", [])}
    patterns = include or cfg["default_files"]
    skip = cfg.get("skip_files", [])
    names = files or sorted(n for n in siblings if "/" not in n and any(fnmatch.fnmatch(n, p) for p in patterns)
                            and not any(fnmatch.fnmatch(n, x) for x in skip))
    missing = [n for n in names if n not in siblings]
    if missing or not names:
        raise ModelsError(f"{repo} at {commit[:12]} has no {', '.join(missing) if missing else 'file matching ' + ', '.join(patterns)}")
    pinned = []
    for name in names:
        lfs = siblings[name].get("lfs") or {}
        if lfs.get("sha256"):
            pinned.append(File(name, lfs["sha256"], int(lfs["size"])))
            continue
        try:
            data = _get(file_url(base, repo, commit, name))
        except OSError as e:
            raise ModelsError(f"can't download {repo}/{name} at {commit[:12]} to hash it: {e}") from None
        pinned.append(File(name, hashlib.sha256(data).hexdigest(), len(data)))
    return Model(repo, commit, licence, tuple(pinned))


def upsert(models: list[Model], new: Model) -> list[Model]:
    """`models` with `new` in place of the same repository's entry, or added at the end."""
    out = [new if m.repo == new.repo else m for m in models]
    return out if any(m.repo == new.repo for m in models) else out + [new]
