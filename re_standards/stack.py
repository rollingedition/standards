"""A terminal book's stack: what runs beside its steps, pinned so every run is the same.

book.toml says which Lab a book has and what it runs:

    [lab]
    kind = "terminal"           # or "notebook", today's Lab: the default
    stack = "k3s"               # "k3s", "compose" or "none" (the default)

The author writes examples/stack.in.toml, the versions they choose:

    [tools]
    k3s = "v1.31.4+k3s1"
    kubectl = "v1.31.4"
    k3d = "v5.7.5"

    [charts.strimzi-kafka-operator]
    repo = "https://strimzi.io/charts/"
    version = "0.45.0"
    licence = "Apache-2.0"

    [images."quay.io/strimzi/kafka:0.45.0-kafka-3.9.0"]
    licence = "Apache-2.0"

and `re-check stack --pin` generates examples/stack.toml from it, never typed: each tool's file for each platform it
runs on, by URL and SHA-256 (data/commands.toml, [stack.tools]); each chart's archive by URL and SHA-256, from its
repository's index; each image by digest, from its registry; and every licence. A licence must be on [licences]
allowed and match nothing on refused. `re-check stack` checks both files: stack.toml in step with stack.in.toml, every
pin complete, every licence allowed. {{version:k3s}} binds from stack.toml as {{version:pandas}} does from
requirements.txt.

A book with no .py example needs no Python runtime: its examples check passes with nothing to build.

A compose stack's services are in examples/compose.yaml, which the author writes: every image named by a digest
stack.toml pins (REF@sha256:…), nothing built, no port beyond loopback, nothing privileged or on the host's network,
and no mount outside the book's examples folder (compose_problems).
"""
from __future__ import annotations

import hashlib
import json
import re
import tomllib
import urllib.parse
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from . import steps as step_format

STACK_IN = "examples/stack.in.toml"
STACK = "examples/stack.toml"
COMPOSE = "examples/compose.yaml"           # a compose stack's services, every image by a digest stack.toml pins
SHA256 = re.compile(r"^[0-9a-f]{64}$")
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
IMAGE = re.compile(r"^(?:(?P<registry>[a-z0-9.-]+(?::\d+)?)/)?(?P<repo>[a-z0-9]+(?:[._/-][a-z0-9]+)*):(?P<tag>[\w][\w.+-]{0,127})$")
HEADER = ("# The stack's pins: every tool's files by URL and SHA-256, every chart's archive, and every image by digest,\n"
          "# with their licences. Generated by `re-check stack --pin` from examples/stack.in.toml; don't edit by hand.\n")
AGENT = "re-standards (stack pins)"


class StackError(ValueError):
    """The stack's files are malformed, or a pin can't be made."""


def settings() -> dict:
    return step_format.settings()


# ---------------------------------------------------------------- book.toml's [lab]


def lab(manifest: dict | None) -> dict:
    """The book's [lab], with its defaults: kind and stack."""
    cfg = settings()["stack"]
    given = (manifest or {}).get("lab") or {}
    return {"kind": given.get("kind", cfg["default_kind"]), "stack": given.get("stack", cfg["default_stack"])}


def is_terminal(manifest: dict | None) -> bool:
    return lab(manifest)["kind"] == "terminal"


def manifest_problems(manifest: dict) -> list[str]:
    """What book.toml's [lab] gets wrong, for `re-check manifest`."""
    if "lab" not in manifest:
        return []
    cfg, given = settings()["stack"], manifest["lab"]
    who = manifest.get("slug", "?")
    if not isinstance(given, dict):
        return [f"{who}: [lab] is a table, with kind and stack"]
    out = []
    if unknown := sorted(set(given) - {"kind", "stack"}):
        out.append(f"{who}: [lab] takes kind and stack, not {', '.join(unknown)}")
    if given.get("kind", cfg["default_kind"]) not in cfg["lab_kinds"]:
        out.append(f"{who}: [lab] kind is one of {', '.join(cfg['lab_kinds'])}")
    if given.get("stack", cfg["default_stack"]) not in cfg["kinds"]:
        out.append(f"{who}: [lab] stack is one of {', '.join(cfg['kinds'])}")
    return out


# ---------------------------------------------------------------- licences


def licence_problem(expression: str, what: str) -> str | None:
    """Why a licence, an SPDX expression, can't ship in a Lab's stack, or None. In an AND every licence must be
    allowed; in an OR one allowed is enough. A refused one is named with what to use instead, when there's a word
    for it in `what`'s name."""
    cfg = settings()["licences"]
    allowed, refused = set(cfg["allowed"]), [re.compile(p) for p in cfg["refused"]]
    if not expression or not expression.strip():
        return f"{what}: give its licence, as an SPDX identifier such as {cfg['preferred']}"

    def verdict(term: str) -> str:
        term = term.strip().strip("()").strip()
        if any(p.search(term) for p in refused):
            return "refused"
        return "allowed" if term in allowed else "unknown"

    alternatives = [[verdict(t) for t in re.split(r"\s+AND\s+|\s+WITH\s+", alt)]
                    for alt in re.split(r"\s+OR\s+", expression.strip())]
    if any(all(v == "allowed" for v in alt) for alt in alternatives):
        return None
    if any("refused" in alt for alt in alternatives):
        instead = next((use for word, use in cfg["instead"].items() if word in what.lower()), "")
        return (f"{what}: {expression} isn't open source enough for a Lab: it restricts offering the software as a "
                f"service, or isn't open source" + (f"; use {instead} instead" if instead else ""))
    return f"{what}: {expression} isn't on the allowed list of licences; it's refused until it's read and added"


# ---------------------------------------------------------------- the two files


@dataclass
class Pinned:
    """examples/stack.toml, read."""
    stack: str
    source_sha256: str
    tools: dict[str, dict] = field(default_factory=dict)       # name -> {version, licence, platforms: {p: {url, sha256}}}
    charts: list[dict] = field(default_factory=list)            # {name, repo, version, url, sha256, licence}
    images: list[dict] = field(default_factory=list)            # {ref, digest, licence}

    def versions(self) -> dict[str, str]:
        """What {{version:NAME}} binds to: each tool's version and each chart's."""
        out = {name.lower(): t["version"] for name, t in self.tools.items()}
        out.update({c["name"].lower(): c["version"] for c in self.charts})
        return out

    def digest(self) -> str:
        """The pins' hash: a change to any of them runs every chapter again."""
        return hashlib.sha256(json.dumps({"stack": self.stack, "tools": self.tools, "charts": self.charts,
                                          "images": self.images}, sort_keys=True).encode()).hexdigest()


def read_source(root: Path) -> tuple[dict | None, str]:
    path = Path(root) / STACK_IN
    if not path.exists():
        return None, ""
    text = path.read_text(encoding="utf-8")
    try:
        return tomllib.loads(text), text
    except tomllib.TOMLDecodeError as e:
        raise StackError(f"{STACK_IN} isn't valid TOML: {e}") from None


def source_problems(data: dict) -> list[str]:
    """What stack.in.toml gets wrong before anything is fetched."""
    cfg = settings()["stack"]
    out = []
    if unknown := sorted(set(data) - {"tools", "charts", "images"}):
        out.append(f"{STACK_IN}: only [tools], [charts.NAME] and [images.\"REF\"] belong here, not {', '.join(unknown)}")
    for name, version in (data.get("tools") or {}).items():
        if name not in cfg["tools"]:
            out.append(f"{STACK_IN}: [tools] {name} isn't a tool a stack can pin; the tools are {', '.join(cfg['tools'])}")
        elif not isinstance(version, str) or not version.strip():
            out.append(f"{STACK_IN}: [tools] {name} needs its exact version, such as \"v1.31.4\"")
    for name, chart in (data.get("charts") or {}).items():
        if not isinstance(chart, dict) or not chart.get("repo") or not chart.get("version"):
            out.append(f"{STACK_IN}: [charts.{name}] needs repo and version")
        elif not str(chart["repo"]).startswith("https://"):
            out.append(f"{STACK_IN}: [charts.{name}] repo is a chart repository's https:// URL")
    for ref, image in (data.get("images") or {}).items():
        if not IMAGE.match(ref):
            out.append(f"{STACK_IN}: {ref!r} isn't an image with a tag, such as \"quay.io/strimzi/kafka:0.45.0\"")
        elif ref.rsplit(":", 1)[1] == "latest":
            out.append(f"{STACK_IN}: {ref} is the latest tag, which the cluster pulls every time and which moves: pin an "
                       "image's own version")
        if not isinstance(image, dict):
            out.append(f"{STACK_IN}: [images.\"{ref}\"] is a table, with its licence")
    return out


def parse_pinned(text: str) -> Pinned:
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise StackError(f"{STACK} isn't valid TOML: {e}") from None
    return Pinned(stack=data.get("stack", ""), source_sha256=data.get("source_sha256", ""),
                  tools=data.get("tools") or {}, charts=data.get("charts") or [], images=data.get("images") or [])


def read_pinned(root: Path) -> Pinned | None:
    path = Path(root) / STACK
    return parse_pinned(path.read_text(encoding="utf-8")) if path.exists() else None


def versions(root: Path) -> dict[str, str]:
    """{{version:NAME}}'s values from examples/stack.toml, or nothing for a book without one."""
    try:
        pinned = read_pinned(root)
    except (StackError, OSError):
        return {}
    return pinned.versions() if pinned else {}


def pinned_problems(pinned: Pinned, stack: str, source_text: str) -> list[str]:
    """What stack.toml gets wrong: out of step with stack.in.toml, a pin missing its hash or digest, a tool the stack
    needs missing, a licence not allowed."""
    cfg = settings()["stack"]
    out = []
    if pinned.stack != stack:
        out.append(f"{STACK} pins a {pinned.stack or 'missing'} stack, and book.toml's [lab] stack is {stack}: run "
                   "re-check stack --pin")
    if pinned.source_sha256 != hashlib.sha256(source_text.encode()).hexdigest():
        out.append(f"{STACK} is out of date with {STACK_IN}: run re-check stack --pin")
    for name in cfg["requires"].get(stack, []):
        if name not in pinned.tools:
            out.append(f"a {stack} stack needs {name}: add it to {STACK_IN}'s [tools], then run re-check stack --pin")
    for name, tool in sorted(pinned.tools.items()):
        catalog = cfg["tools"].get(name)
        if catalog is None:
            out.append(f"{STACK}: {name} isn't a tool a stack can pin")
            continue
        for platform in catalog["platforms"]:
            entry = (tool.get("platforms") or {}).get(platform) or {}
            if not entry.get("url", "").startswith("https://") or not SHA256.match(entry.get("sha256", "")):
                out.append(f"{STACK}: {name} {tool.get('version', '?')} has no file with a SHA-256 for {platform}")
        if catalog.get("airgap_url") and not SHA256.match((tool.get("airgap") or {}).get("sha256", "")):
            out.append(f"{STACK}: {name}'s airgap images have no SHA-256")
        if catalog.get("image") and not DIGEST.match((tool.get("image") or {}).get("digest", "")):
            out.append(f"{STACK}: {name}'s image for readers' machines has no digest")
        if why := licence_problem(tool.get("licence", ""), name):
            out.append(why)
    for chart in pinned.charts:
        what = f"chart {chart.get('name', '?')} {chart.get('version', '')}".strip()
        if not str(chart.get("url", "")).startswith("https://") or not SHA256.match(chart.get("sha256", "")):
            out.append(f"{STACK}: {what} has no archive with a SHA-256")
        if why := licence_problem(chart.get("licence", ""), what):
            out.append(why)
    for image in pinned.images:
        what = f"image {image.get('ref', '?')}"
        if not DIGEST.match(image.get("digest", "")):
            out.append(f"{STACK}: {what} isn't pinned by digest")
        if why := licence_problem(image.get("licence", ""), what):
            out.append(why)
    return out


MANIFEST_IMAGE = re.compile(r"""^\s*(?:-\s*)?image:\s*["']?([^"'\s#]+)""", re.MULTILINE)
PULL_ALWAYS = re.compile(r"""^\s*(?:-\s*)?imagePullPolicy:\s*["']?Always\b""", re.MULTILINE)


def full_ref(ref: str) -> str:
    """An image's name as the cluster keeps it, Docker Hub's written out: "postgres:16" -> docker.io/library/postgres:16."""
    registry, repo, tag = _registry(ref)
    return f"{registry}/{repo}:{tag}"


def image_problems(root: Path, pinned: Pinned) -> list[str]:
    """W-74: each image the book's manifests (examples/**/*.yaml) name is one the stack pins, by its tag, never by a
    digest the cluster can't find or as latest, and none asks to be pulled every time: a Lab's cluster has no registry."""
    pinned_refs = {full_ref(i["ref"]) for i in pinned.images if IMAGE.match(i.get("ref", ""))}
    out = []
    for path in sorted(p for pattern in ("*.yaml", "*.yml") for p in (Path(root) / "examples").rglob(pattern)):
        rel = path.relative_to(root).as_posix()
        if rel == COMPOSE:
            continue                                      # a compose stack's file names its images by digest
                                                          # (compose_problems), since docker compose pulls by tag
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in MANIFEST_IMAGE.finditer(text):
            ref, line = m.group(1), text.count("\n", 0, m.start()) + 1
            if "{{" in ref or "$" in ref:
                continue                                  # a template's value, filled in elsewhere
            if "@" in ref:
                out.append(f"{rel}:{line}: {ref} names an image by digest: name it by the tag {STACK} pins, which "
                           "holds its digest")
            elif not IMAGE.match(ref) or ref.rsplit(":", 1)[1] == "latest":
                out.append(f"{rel}:{line}: {ref} has no version of its own: name it by the tag {STACK} pins")
            elif full_ref(ref) not in pinned_refs:
                out.append(f"{rel}:{line}: {ref} isn't an image {STACK} pins, so the cluster can't run it: add it to "
                           f"{STACK_IN}'s [images], then run re-check stack --pin")
        for m in PULL_ALWAYS.finditer(text):
            out.append(f"{rel}:{text.count(chr(10), 0, m.start()) + 1}: imagePullPolicy: Always pulls every time, and a "
                       "Lab's cluster has no registry: leave it out, or write IfNotPresent")
    return out


def check(root: Path, manifest: dict | None) -> tuple[list[str], Pinned | None]:
    """`re-check stack`: (problems, the pins). A book whose Lab is the notebook Lab, with no stack files, has none."""
    root = Path(root)
    stack = lab(manifest)["stack"]
    problems = manifest_problems(manifest or {})
    try:
        source, text = read_source(root)
        pinned = read_pinned(root)
    except StackError as e:
        return problems + [str(e)], None
    if source is None:
        if pinned is not None:
            problems.append(f"{STACK} is generated from {STACK_IN}, which is missing")
        elif settings()["stack"]["requires"].get(stack):
            problems.append(f"a {stack} stack is pinned in {STACK_IN}: write its [tools], then run re-check stack --pin")
        return problems, pinned
    problems += source_problems(source)
    if pinned is not None:
        problems += pinned_problems(pinned, stack, text) + image_problems(root, pinned)
        return problems + (compose_problems(root, pinned) if stack == "compose" else []), pinned
    for ref, image in (source.get("images") or {}).items():           # what --pin would refuse, said before it runs
        if isinstance(image, dict) and (why := licence_problem(image.get("licence", ""), f"image {ref}")):
            problems.append(why)
    for name, chart in (source.get("charts") or {}).items():
        if isinstance(chart, dict) and (why := licence_problem(chart.get("licence", ""), f"chart {name}")):
            problems.append(why)
    return problems + [f"{STACK} is missing: run re-check stack --pin"], None


# ---------------------------------------------------------------- a compose stack's file (TL13)


def compose_problems(root: Path, pinned: Pinned | None) -> list[str]:
    """What examples/compose.yaml gets wrong for a compose stack: every service's image named by a digest stack.toml
    pins, nothing built, no port beyond loopback, nothing privileged, on the host's network, or mounting a path outside
    the book's examples folder."""
    import yaml
    path = Path(root) / COMPOSE
    if not path.exists():
        return [f"a compose stack's services are in {COMPOSE}: write it, every image by its digest"]
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        return [f"{COMPOSE} isn't valid YAML: {e}"]
    services = data.get("services") if isinstance(data, dict) else None
    if not isinstance(services, dict) or not services:
        return [f"{COMPOSE} names its services under services:"]
    pins = {f"{i.get('ref')}@{i.get('digest')}" for i in (pinned.images if pinned else [])}
    out = []
    for name, svc in services.items():
        what = f"{COMPOSE}: service {name}"
        if not isinstance(svc, dict):
            out.append(f"{what} is a table")
            continue
        image = str(svc.get("image", ""))
        if "@sha256:" not in image:
            out.append(f"{what}'s image is named by its digest, REF@sha256:…, as stack.toml pins it, not {image or 'none'}")
        elif image not in pins:
            out.append(f"{what}'s image {image} isn't one stack.toml pins: add it to {STACK_IN}, run re-check stack "
                       "--pin, and name it by the digest it writes")
        if "build" in svc:
            out.append(f"{what} builds an image: a stack runs pinned images alone")
        if svc.get("privileged") or svc.get("network_mode") == "host" or svc.get("pid") == "host":
            out.append(f"{what} runs privileged, or on the host's network or processes: no stack may")
        for port in svc.get("ports") or []:
            text = str(port.get("host_ip", "") + ":" + str(port.get("published", "")) if isinstance(port, dict) else port)
            if not (text.startswith("127.0.0.1:") or text.startswith("[::1]:")):
                out.append(f"{what} publishes {port} beyond loopback: write it as 127.0.0.1:PORT:PORT")
        for volume in svc.get("volumes") or []:
            source = volume.get("source", "") if isinstance(volume, dict) else str(volume).split(":", 1)[0]
            if str(source).startswith(("/", "~")) or ".." in str(source).split("/"):
                out.append(f"{what} mounts {source}, outside the book's examples folder")
    return out


# ---------------------------------------------------------------- pinning (needs the internet)


Fetch = Callable[[str, dict], tuple[bytes, dict]]


def http_fetch(url: str, headers: dict) -> tuple[bytes, dict]:
    """GET `url`: (body, headers, lowercased). Only public files and registries: no credential is ever sent."""
    req = urllib.request.Request(url, headers={"User-Agent": AGENT, **headers})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read(), {k.lower(): v for k, v in r.headers.items()}


def _fill(template: str, version: str, platform: str = "") -> str:
    os_, _, arch = platform.partition("-")
    return template.format(version=version, version_url=urllib.parse.quote(version, safe=""), os=os_, arch=arch)


def _sha256_listed(listing: str, name: str) -> str | None:
    for line in listing.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-1].lstrip("*").split("/")[-1] == name and SHA256.match(parts[0].lower()):
            return parts[0].lower()
    return None


def _first_hash(text: str) -> str | None:
    word = (text.split() or [""])[0].lower()
    return word if SHA256.match(word) else None


def pin_tool(name: str, version: str, fetch: Fetch) -> dict:
    catalog = settings()["stack"]["tools"][name]
    out: dict = {"version": version, "licence": catalog["licence"], "platforms": {}}
    for platform in catalog["platforms"]:
        url = _fill(catalog["url"], version, platform)
        if catalog.get("checksums"):
            listing = fetch(_fill(catalog["checksums"], version, platform), {})[0].decode("utf-8", "replace")
            sha = _sha256_listed(listing, _fill(catalog.get("name", url.rsplit("/", 1)[-1]), version, platform))
        else:
            sha = _first_hash(fetch(_fill(catalog["sha256_url"], version, platform), {})[0].decode("utf-8", "replace"))
        if not sha:
            raise StackError(f"{name} {version}: no SHA-256 for {platform} was published beside {url}")
        out["platforms"][platform] = {"url": url, "sha256": sha}
    if catalog.get("airgap_url"):
        listing = fetch(_fill(catalog["checksums"], version), {})[0].decode("utf-8", "replace")
        sha = _sha256_listed(listing, catalog["airgap_name"])
        if not sha:
            raise StackError(f"{name} {version}: no SHA-256 was published for {catalog['airgap_name']}")
        out["airgap"] = {"url": _fill(catalog["airgap_url"], version), "sha256": sha}
    if catalog.get("image"):
        ref = f"{catalog['image']}:{version.replace('+', '-')}"
        out["image"] = {"ref": ref, "digest": image_digest(ref, fetch)}
    return out


MANIFEST_TYPES = ", ".join(("application/vnd.oci.image.index.v1+json",
                            "application/vnd.docker.distribution.manifest.list.v2+json",
                            "application/vnd.oci.image.manifest.v1+json",
                            "application/vnd.docker.distribution.manifest.v2+json"))


def _registry(ref: str) -> tuple[str, str, str]:
    m = IMAGE.match(ref)
    if not m:
        raise StackError(f"{ref!r} isn't an image with a tag")
    registry, repo = m.group("registry") or "docker.io", m.group("repo")
    if registry == "docker.io" and "/" not in repo:
        repo = f"library/{repo}"
    return registry, repo, m.group("tag")


def image_digest(ref: str, fetch: Fetch) -> str:
    """An image tag's digest, from its registry's manifest, anonymously: the index's for a multi-platform image, so the
    same digest serves the Lab's machine and a reader's."""
    registry, repo, tag = _registry(ref)
    host = "registry-1.docker.io" if registry == "docker.io" else registry
    headers = {"Accept": MANIFEST_TYPES}
    token = _anonymous_token(registry, repo, fetch)
    if token:
        headers["Authorization"] = f"Bearer {token}"
    _, got = fetch(f"https://{host}/v2/{repo}/manifests/{tag}", headers)
    digest = got.get("docker-content-digest", "")
    if not DIGEST.match(digest):
        raise StackError(f"{ref}: its registry gave no digest")
    return digest


def _anonymous_token(registry: str, repo: str, fetch: Fetch) -> str:
    """A pull token for a public repository, where the registry asks for one: Docker Hub's, GitHub's and Quay's are
    given to anyone."""
    services = {"docker.io": "https://auth.docker.io/token?service=registry.docker.io&scope=repository:{repo}:pull",
                "ghcr.io": "https://ghcr.io/token?scope=repository:{repo}:pull",
                "quay.io": "https://quay.io/v2/auth?service=quay.io&scope=repository:{repo}:pull"}
    if registry not in services:
        return ""
    body, _ = fetch(services[registry].format(repo=repo), {})
    try:
        data = json.loads(body)
    except ValueError:
        return ""
    return data.get("token") or data.get("access_token") or ""


def pin_chart(name: str, chart: dict, fetch: Fetch) -> dict:
    """A chart's archive by URL and SHA-256, from its repository's index.yaml, which lists each version's digest."""
    import yaml
    repo = str(chart["repo"]).rstrip("/") + "/"
    index = yaml.safe_load(fetch(urllib.parse.urljoin(repo, "index.yaml"), {})[0]) or {}
    entry = next((e for e in (index.get("entries") or {}).get(name, []) if str(e.get("version")) == str(chart["version"])),
                 None)
    if entry is None:
        raise StackError(f"chart {name} {chart['version']} isn't in {repo}index.yaml")
    url = urllib.parse.urljoin(repo, (entry.get("urls") or [""])[0])
    if not SHA256.match(str(entry.get("digest", ""))):
        raise StackError(f"chart {name} {chart['version']}: {repo}index.yaml gives no SHA-256 for it")
    return {"name": name, "repo": chart["repo"], "version": str(chart["version"]), "url": url,
            "sha256": entry["digest"], "licence": chart.get("licence", "")}


def pin(root: Path, manifest: dict | None, fetch: Fetch = http_fetch) -> str:
    """examples/stack.toml's text, generated from examples/stack.in.toml."""
    source, text = read_source(Path(root))
    if source is None:
        raise StackError(f"{STACK_IN} is missing: write the versions the book uses there first")
    if problems := source_problems(source):
        raise StackError("\n".join(problems))
    tools = {name: pin_tool(name, version, fetch) for name, version in sorted((source.get("tools") or {}).items())}
    charts = [pin_chart(name, chart, fetch) for name, chart in sorted((source.get("charts") or {}).items())]
    images = [{"ref": ref, "digest": image_digest(ref, fetch), "licence": (image or {}).get("licence", "")}
              for ref, image in sorted((source.get("images") or {}).items())]
    pinned = Pinned(lab(manifest)["stack"], hashlib.sha256(text.encode()).hexdigest(), tools, charts, images)
    return to_toml(pinned)


def _value(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def to_toml(p: Pinned) -> str:
    lines = [HEADER.rstrip("\n"), f"stack = {_value(p.stack)}", f"source_sha256 = {_value(p.source_sha256)}"]
    for name, tool in sorted(p.tools.items()):
        lines += ["", f"[tools.{name}]", f"version = {_value(tool['version'])}", f"licence = {_value(tool['licence'])}"]
        for key in ("airgap", "image"):
            if key in tool:
                inner = ", ".join(f"{k} = {_value(v)}" for k, v in tool[key].items())
                lines.append(f"{key} = {{ {inner} }}")
        for platform, entry in sorted(tool["platforms"].items()):
            lines += [f"[tools.{name}.platforms.{platform}]", f"url = {_value(entry['url'])}",
                      f"sha256 = {_value(entry['sha256'])}"]
    for chart in p.charts:
        lines += ["", "[[charts]]"] + [f"{k} = {_value(chart[k])}" for k in ("name", "repo", "version", "url", "sha256",
                                                                               "licence")]
    for image in p.images:
        lines += ["", "[[images]]"] + [f"{k} = {_value(image[k])}" for k in ("ref", "digest", "licence")]
    return "\n".join(lines) + "\n"
