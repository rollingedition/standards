import json
import re

import yaml

from re_standards import bookfmt, readme
from bookkit import make_book

MANIFEST_EXTRA = 'reader = "For people who like small tests."\n'


def book_at(tmp_path, extra=MANIFEST_EXTRA):
    from bookkit import MANIFEST
    root = make_book(tmp_path, manifest=MANIFEST + extra)
    return bookfmt.load_book(root)


def test_readme_is_generated_from_the_book(tmp_path):
    book = book_at(tmp_path)
    text = readme.readme(book)
    assert text.startswith("<!-- Generated by re-check readme")
    assert "# Tiny Book" in text and "By Rolling Edition, with AI · **Foundations**" in text
    assert "For people who like small tests." in text
    assert "| 1 | [First steps](https://rollingedition.com/tiny-book/first-steps) · [source](chapters/01-first-steps.md) | Opening text | 1 |" in text
    assert "https://rollingedition.com/tiny-book/stamp.svg" in text and "Written with AI. Verified by people." in text
    # a released book's front page shows its cover, stamp badge, Checks badge and the footer icon
    assert '<img src="https://rollingedition.com/tiny-book/cover.svg"' in text
    assert "[![Checks](https://github.com/rollingedition/book-tiny-book/actions/workflows/checks.yml/badge.svg)]" in text
    assert '<img src="https://rollingedition.com/assets/logos/rolling-edition-icon.svg" width="28" alt="">' in text


def test_a_draft_book_reads_as_an_unpublished_draft(tmp_path):
    from bookkit import MANIFEST
    root = make_book(tmp_path, manifest=MANIFEST.replace('status = "live"', 'status = "draft"') + MANIFEST_EXTRA)
    text = readme.readme(bookfmt.load_book(root))
    assert "By Rolling Edition, with AI · **Foundations**\n" in text and "Read the preview" not in text and "/previews/" not in text
    assert "| 1 | [First steps](chapters/01-first-steps.md) |" in text                   # no public pages yet
    assert "**Draft: not yet published.** Its first edition is published once agents have reviewed every chapter and " \
           "every example passes" in text                                           # no person approves it
    assert "not yet verified" not in text and not re.search(r"\bD-\d", text)       # no private decision IDs
    assert "community reviewers" not in text and "approved" not in text
    for absent in ("cover.svg", "stamp.svg", "Verified by people", "/tiny-book/changes", "Check a copy"):
        assert absent not in text, absent


def test_a_draft_readme_carries_no_images(tmp_path):
    """A draft's repository is private and its checks run only on pull requests, so a Checks badge has nothing to
    show; the site that would serve the mark isn't live yet. The text and links stay."""
    from bookkit import MANIFEST
    root = make_book(tmp_path, manifest=MANIFEST.replace('status = "live"', 'status = "draft"') + MANIFEST_EXTRA)
    text = readme.readme(bookfmt.load_book(root))
    for image in ("![", "<img", "badge.svg", "rolling-edition-icon.svg"):
        assert image not in text, image
    assert text.rstrip().endswith("Rolling Edition publishes free technical books that AI drafts, people verify, and an "
                                  "automated pipeline keeps current. [rollingedition.com](https://rollingedition.com)")
    assert "A test book.\n\n**Draft: not yet published.**" in text            # the summary, then the banner


def test_the_front_page_describes_open_verification(tmp_path):
    """Open verification: agents publish, anyone checks or corrects, and serious risks go to a person. It never says that a person
    approved anything, and credits contributors by name or pseudonym."""
    text = readme.readme(book_at(tmp_path))
    current = text.split("## How this book stays current\n\n", 1)[1].split("\n\n", 1)[0]
    assert "Agents draft any fix and check every change, and a change merges once its checks pass" in current
    assert "waits for a Rolling Edition maintainer" in current and "Anyone can check the book or correct it" in current
    assert "its examples passing and what changed." in current
    for claim in ("approved", "reviewers", "the community reviews", "review every change"):
        assert claim not in text, claim
    assert "credited by name or pseudonym" in text and "and it merges once they pass" in text
    assert f"[Report it]({readme.report_error_url('tiny-book', readme.load_config())}) with the section's ID: the last part " \
           "of the link beside each heading on rollingedition.com." in text


def test_a_level_stands_in_when_there_is_no_reader_sentence(tmp_path):
    assert "For readers new to the field." in readme.readme(book_at(tmp_path, extra=""))
    cfg = readme.load_config()                                     # the site's book page reads the same sentence
    assert readme.reader({"level": "foundations"}, cfg) == "For readers new to the field."
    assert readme.reader({"level": "foundations", "reader": "For people who like small tests."}, cfg) == "For people who like small tests."


def test_citation_cites_the_book_without_an_edition(tmp_path):
    cff = yaml.safe_load(readme.citation(book_at(tmp_path)))
    assert cff["cff-version"] == "1.2.0" and cff["title"] == "Tiny Book"
    assert cff["authors"] == [{"name": "Rolling Edition"}] and "version" not in cff
    assert cff["preferred-citation"]["type"] == "book" and cff["license"] == ["CC-BY-4.0", "MIT"]


def test_check_finds_stale_files_and_write_fixes_them(tmp_path):
    book = book_at(tmp_path)
    assert len(readme.check(book)) == 5
    assert readme.check(book, write=True) == []
    assert readme.check(book) == []
    (book.root / "README.md").write_text("edited by hand\n")
    assert readme.check(book) == ["README.md is out of date; run re-check readme --write"]
    assert "Copyright (c) Rolling Edition and contributors" in (book.root / "LICENSE-CODE").read_text()
    assert (book.root / "LICENSE").read_text().startswith("Attribution 4.0 International")


def test_the_front_page_asks_reusers_to_credit_and_link_back(tmp_path):
    """The full reuse wording, as the site words it ([reuse]): CC BY 4.0 asks for credit, a link to the licence and a note
    of changes, and MIT for its notice, named as LICENSE-CODE names it."""
    text = readme.readme(book_at(tmp_path))
    licence = text.split("## Licence\n\n", 1)[1]
    assert ("Book text is CC BY 4.0: credit Rolling Edition, link back to the book and to the licence, and say what you "
            "changed. Code examples are MIT: keep the notice “Copyright (c) Rolling Edition and contributors” and the MIT "
            "terms with any code you copy. We'd be glad of a link back for the code, too.") in licence
    assert readme.reuse(readme.load_config()) in licence and "{copyright}" not in text


def test_every_book_gets_the_same_renovate_config_with_a_release_age(tmp_path):
    book = book_at(tmp_path)
    readme.check(book, write=True)
    config = json.loads((book.root / "renovate.json").read_text())
    assert config == readme.renovate_config() and config["description"].startswith("Generated by re-check readme")
    assert config["minimumReleaseAge"] == "3 days" and config["osvVulnerabilityAlerts"] is True
    assert config["labels"] == ["kind:deps"] and config["packageRules"][0]["addLabels"] == ["breaking"]
    (book.root / "renovate.json").write_text(json.dumps({**config, "minimumReleaseAge": None}))
    assert readme.check(book) == ["renovate.json is out of date; run re-check readme --write"]


def test_this_repository_carries_its_own_generated_licences():
    licences = readme.own_licences()
    assert licences["LICENSE"].startswith("MIT License") and "Rolling Edition and contributors" in licences["LICENSE"]
    assert "Attribution 4.0 International" in licences["LICENSE-TEXT"]
    assert readme.check_own_licences() == []
