"""A terminal book's local lab: lab/start.sh, chapter.sh, check.sh and stop.sh, so anyone can work through the book on
their own machine, free, with nothing of ours.

`re-check lab --write` generates them from book.toml, the chapters' steps and checks, and examples/stack.toml; `re-check
lab` fails when they're out of date. Never typed. They're POSIX sh, for Linux (x86-64 and Arm) and macOS on Apple
silicon, and they run the book's own step files with bash:

    lab/start.sh                 a workspace with the book's files, under ~/.rolling-edition/{slug} (or $RE_LAB_HOME),
                                 and for a k3s stack a cluster in Docker through k3d, every tool fetched at its pinned
                                 SHA-256 and k3s's image by digest
    lab/chapter.sh CHAPTER_ID    a fresh start for that chapter: the workspace (and cluster) made again, then the
                                 chapter's setup steps run, each one's waits polled
    lab/check.sh ID ...          each check, or every check of a chapter: Passed, or Not yet with its hint
    lab/stop.sh                  the cluster deleted; the reader's files stay

The reader runs each step themselves, copied from the page, in the workspace that `. ~/.rolling-edition/{slug}/env.sh`
opens.
"""
from __future__ import annotations

import re
import shlex
from pathlib import Path

from . import stack as stack_pins

SCRIPTS = ("start.sh", "chapter.sh", "check.sh", "stop.sh")
HEADER = "# Generated by `re-check lab --write` from book.toml, the chapters' steps and examples/stack.toml. Don't edit by hand."
CLUSTER_NAME_MAX = 32


class LabError(ValueError):
    pass


def q(text: str) -> str:
    return shlex.quote(text)


def fn(step_id: str) -> str:
    return "step_" + re.sub(r"[^a-z0-9]", "_", step_id)


def _prelude(book, purpose: str) -> list[str]:
    which = stack_pins.lab(book.manifest)
    return [
        "#!/bin/sh",
        HEADER,
        f"# {purpose}",
        "set -eu",
        'book_dir=$(cd "$(dirname "$0")/.." && pwd)',
        f"slug={q(book.slug)}",
        f"stack={q(which['stack'])}",
        'lab_home="${RE_LAB_HOME:-$HOME/.rolling-edition/$slug}"',
        'work="$lab_home/work"',
        'bin="$lab_home/bin"',
        "",
        "say() { printf '%s\\n' \"$*\"; }",
        "fail() { printf '%s\\n' \"$*\" >&2; exit 1; }",
        "",
    ]


def _bash() -> list[str]:
    """The bash the book's steps run with: a newer one where there is one, on the PATH first, then Homebrew's, since
    macOS ships bash 3.2; else whichever there is. The steps keep to bash 3.2 either way (W-76)."""
    return [
        "steps_bash() {",
        "  for b in \"$(command -v bash)\" /opt/homebrew/bin/bash /usr/local/bin/bash; do",
        "    [ -x \"$b\" ] && \"$b\" -c '[ \"${BASH_VERSINFO[0]}\" -ge 4 ]' 2>/dev/null && { printf '%s\\n' \"$b\"; return 0; }",
        "  done",
        "  command -v bash || fail \"The book's steps run with bash: install it, then run this again.\"",
        "}",
        "bash_bin=$(steps_bash)",
        "",
    ]


def _cluster(book) -> str:
    name = f"re-{book.slug}"[:CLUSTER_NAME_MAX].rstrip("-")
    return name


def _tools(pinned: stack_pins.Pinned | None) -> list[str]:
    """The platform, the pinned tools' files for it, and fetching one checked by its SHA-256."""
    if pinned is None:
        return []
    cases = []
    for name in ("k3d", "kubectl", "helm"):
        tool = pinned.tools.get(name)
        if not tool:
            continue
        for platform, entry in sorted(tool["platforms"].items()):
            cases.append(f"    {name}-{platform}) echo {q(entry['url'])} {q(entry['sha256'])} ;;")
    return [
        "platform() {",
        "  case \"$(uname -s)-$(uname -m)\" in",
        "    Linux-x86_64) echo linux-amd64 ;;",
        "    Linux-aarch64|Linux-arm64) echo linux-arm64 ;;",
        "    Darwin-arm64) echo darwin-arm64 ;;",
        "    *) fail \"This lab runs on Linux, on x86-64 or Arm, and on macOS on Apple silicon, not on $(uname -s) $(uname -m).\" ;;",
        "  esac",
        "}",
        "tool_file() {",
        "  case \"$1-$2\" in",
        *cases,
        "    *) fail \"There's no pinned $1 for $2.\" ;;",
        "  esac",
        "}",
        "sha256_of() {",
        "  if command -v sha256sum >/dev/null 2>&1; then sha256sum \"$1\" | cut -d ' ' -f 1",
        "  else shasum -a 256 \"$1\" | cut -d ' ' -f 1; fi",
        "}",
        "fetch_tool() {",
        "  set -- \"$1\" $(tool_file \"$1\" \"$(platform)\")",
        "  [ -x \"$bin/$1\" ] && [ \"$(cat \"$bin/.$1.sha256\" 2>/dev/null)\" = \"$3\" ] && return 0",
        "  say \"Fetching $1 from $2\"",
        "  curl -fsSL \"$2\" -o \"$bin/.$1.part\" || fail \"Couldn't fetch $2.\"",
        "  [ \"$(sha256_of \"$bin/.$1.part\")\" = \"$3\" ] || { rm -f \"$bin/.$1.part\"; fail \"$2 isn't the file the book pins: its SHA-256 differs.\"; }",
        "  case \"$2\" in",
        "    *.tar.gz) tar -xzf \"$bin/.$1.part\" -C \"$bin\" --strip-components 1 \"$(platform)/$1\" && rm -f \"$bin/.$1.part\" ;;",
        "    *) mv \"$bin/.$1.part\" \"$bin/$1\" ;;",
        "  esac",
        "  chmod +x \"$bin/$1\"",
        "  printf '%s\\n' \"$3\" > \"$bin/.$1.sha256\"",
        "}",
        "",
    ]


def _cluster_functions(book, pinned: stack_pins.Pinned | None) -> list[str]:
    if pinned is None or "k3s" not in pinned.tools:
        return []
    image = pinned.tools["k3s"].get("image") or {}
    ref = f"{image.get('ref', '')}@{image.get('digest', '')}"
    return [
        f"cluster={q(_cluster(book))}",
        f"k3s_version={q(pinned.tools['k3s']['version'])}",
        "start_cluster() {",
        "  command -v docker >/dev/null 2>&1 || fail \"k3d runs the cluster in Docker: install Docker, or Podman with its Docker socket, then run this again.\"",
        "  docker info >/dev/null 2>&1 || fail \"Docker isn't running: start it, then run this again.\"",
        "  \"$bin/k3d\" cluster delete \"$cluster\" >/dev/null 2>&1 || true",
        "  say \"Starting the book's cluster, k3s $k3s_version, in Docker\"",
        f"  \"$bin/k3d\" cluster create \"$cluster\" --image {q(ref)} --no-lb --wait --timeout 300s \\",
        "    --k3s-arg '--disable=traefik@server:0' --k3s-arg '--disable=servicelb@server:0' \\",
        "    --kubeconfig-update-default=false --kubeconfig-switch-context=false >/dev/null",
        "  \"$bin/k3d\" kubeconfig get \"$cluster\" > \"$lab_home/kubeconfig\"",
        "}",
        "",
    ]


def _services_functions(book) -> list[str]:
    """A compose stack's services in Docker, from the workspace's compose.yaml, every image by its pinned digest: down
    with their volumes, then up and healthy, so each chapter starts from fresh services."""
    if stack_pins.lab(book.manifest)["stack"] != "compose":
        return []
    compose = 'docker compose --project-name "$project" --file "$work/compose.yaml"'
    return [
        f"project={q(_cluster(book))}",
        "start_services() {",
        "  command -v docker >/dev/null 2>&1 || fail \"The book's services run in Docker: install Docker, or Podman with its Docker socket, then run this again.\"",
        "  docker info >/dev/null 2>&1 || fail \"Docker isn't running: start it, then run this again.\"",
        "  say \"Starting the book's services in Docker\"",
        f"  {compose} down --volumes >/dev/null 2>&1 || true",
        f"  {compose} up --detach --wait >/dev/null || fail \"The book's services didn't come up: run {compose.replace(chr(34), '')} logs to see why.\"",
        "}",
        "",
    ]


def _workspace() -> list[str]:
    return [
        "fresh_workspace() {",
        "  case \"$work\" in */work) ;; *) fail \"The workspace must be a folder named work, not $work.\" ;; esac",
        "  rm -rf \"$work\"",
        "  mkdir -p \"$work\" \"$bin\"",
        "  cp -R \"$book_dir/examples/.\" \"$work/\"",
        "  rm -f \"$work\"/*.sh",
        "  find \"$work\" -name '*.out' -exec rm -f {} +",
        "}",
        "write_env() {",
        "  {",
        "    printf 'export PATH=\"%s:$PATH\"\\n' \"$bin\"",
        "    [ -f \"$lab_home/kubeconfig\" ] && printf 'export KUBECONFIG=\"%s\"\\n' \"$lab_home/kubeconfig\"",
        "    printf 'cd \"%s\"\\n' \"$work\"",
        "  } > \"$lab_home/env.sh\"",
        "}",
        "",
    ]


def _step_env() -> str:
    return "env NO_COLOR=1 TZ=UTC PATH=\"$bin:$PATH\""


def _runner() -> list[str]:
    return [
        "run_file() {  # a step's file, run with bash in the workspace, and the exit code it should end with",
        "  say \"  $1\"",
        "  if (cd \"$work\" && " + _step_env() + " \"$bash_bin\" \"$book_dir/examples/$1.sh\") > \"$lab_home/last-step.log\" 2>&1",
        "  then code=0; else code=$?; fi",
        "  [ \"$code\" -eq \"$2\" ] || { cat \"$lab_home/last-step.log\" >&2; fail \"Step $1 ended with exit code $code, not $2.\"; }",
        "}",
        "wait_for() {  # seconds, then a command polled until it exits 0",
        "  end=$(( $(date +%s) + $1 ))",
        "  until (cd \"$work\" && " + _step_env() + " \"$bash_bin\" -c \"$2\") >/dev/null 2>&1; do",
        "    [ \"$(date +%s)\" -lt \"$end\" ] || fail \"Waited $1 s for: $2\"",
        "    sleep 1    # this script's own poll; a book's steps never sleep",
        "  done",
        "}",
        "",
    ]


def chapter_sh(book, pinned) -> str:
    out = _prelude(book, "A fresh start for one chapter: the workspace (and the cluster) made again, then the steps "
                         "that bring it to the chapter's start.")
    out += _workspace() + _tools(pinned) + _cluster_functions(book, pinned) + _services_functions(book) + _bash() + _runner()
    used = []
    for c in book.chapters:
        used += [sid for sid in c.setup if sid not in used]
    for sid in used:
        s = book.steps[sid]
        d = s.directives
        body = [f"run_file {q(sid)} {d.expect_exit}"]
        body += [f"wait_for {int(d.timeout)} {q(w)}" for w in d.wait]
        out += [f"{fn(sid)}() {{", *[f"  {line}" for line in body], "}"]
    chapters = [c for c in book.chapters if c.step_embeds]
    out += ["", "[ $# -eq 1 ] || fail \"Usage: lab/chapter.sh CHAPTER_ID, one of: " +
            ", ".join(c.chapter_id for c in chapters) + "\"",
            "[ -d \"$lab_home\" ] || fail \"Run lab/start.sh first.\"",
            "case \"$1\" in"]
    for c in chapters:
        out.append(f"  {c.chapter_id}) setup={q(' '.join(c.setup))} ;;")
    out += ["  *) fail \"There's no chapter $1 with steps. The chapters: " + ", ".join(c.chapter_id for c in chapters) +
            "\" ;;", "esac", "fresh_workspace"]
    if pinned is not None and "k3s" in pinned.tools:
        out += ["start_cluster", "export KUBECONFIG=\"$lab_home/kubeconfig\""]
    if stack_pins.lab(book.manifest)["stack"] == "compose":
        out += ["start_services"]
    out += ["[ -z \"$setup\" ] || say \"Bringing the workspace to the start of $1:\"",
            "for id in $setup; do",
            "  \"step_$(printf '%s' \"$id\" | tr -c 'a-z0-9' '_')\"",
            "done",
            "write_env",
            "say \"Chapter $1 starts here. In your terminal: . $lab_home/env.sh\""]
    return "\n".join(out) + "\n"


def start_sh(book, pinned) -> str:
    compose = stack_pins.lab(book.manifest)["stack"] == "compose"
    out = _prelude(book, "Starts this book's lab on your own machine: a workspace with the book's files" +
                   (", and a k3s cluster in Docker through k3d." if pinned and "k3s" in pinned.tools else
                    ", and its services in Docker." if compose else "."))
    out += _workspace() + _tools(pinned) + _cluster_functions(book, pinned) + _services_functions(book)
    out += ["mkdir -p \"$lab_home\" \"$bin\"", "fresh_workspace"]
    if pinned is not None:
        out += [f"fetch_tool {name}" for name in ("k3d", "kubectl", "helm") if name in pinned.tools]
    if pinned is not None and "k3s" in pinned.tools:
        out += ["start_cluster"]
    if compose:
        out += ["start_services"]
    out += ["write_env",
            "say \"Ready. The workspace is $work.\"",
            "say \"In your terminal: . $lab_home/env.sh\"",
            "say \"Then start any chapter fresh with lab/chapter.sh CHAPTER_ID, and check your work with lab/check.sh.\""]
    return "\n".join(out) + "\n"


def check_sh(book) -> str:
    out = _prelude(book, "Checks your work: each check, or every check of a chapter, says Passed or Not yet.") + _bash()
    checks = [(c.chapter_id, e.example_id) for c in book.chapters for e in c.step_embeds if e.kind == "check"]
    out += ["check_info() {", "  case \"$1\" in"]
    for _, cid in checks:
        d = book.steps[cid].directives
        out.append(f"    {cid}) expect={d.expect_exit}; hint={q(d.hint)} ;;")
    out += ["    *) return 1 ;;", "  esac", "}", "chapter_checks() {", "  case \"$1\" in"]
    for chapter in dict.fromkeys(ch for ch, _ in checks):
        out.append(f"    {chapter}) echo {q(' '.join(cid for ch, cid in checks if ch == chapter))} ;;")
    out += ["    *) return 1 ;;", "  esac", "}",
            "[ $# -gt 0 ] || fail \"Usage: lab/check.sh CHECK_ID or CHAPTER_ID ... The checks: " +
            ", ".join(cid for _, cid in checks) + "\"",
            "[ -d \"$work\" ] || fail \"Run lab/start.sh first.\"",
            "[ ! -f \"$lab_home/kubeconfig\" ] || export KUBECONFIG=\"$lab_home/kubeconfig\"",
            "case \"$PWD/\" in \"$work\"/*) here=\"$PWD\" ;; *) here=\"$work\" ;; esac",
            "status=0",
            "for given in \"$@\"; do",
            "  ids=$(chapter_checks \"$given\" || echo \"$given\")",
            "  for id in $ids; do",
            "    check_info \"$id\" || fail \"There's no check $id.\"",
            "    if (cd \"$here\" && " + _step_env() +
            " \"$bash_bin\" \"$book_dir/examples/$id.sh\") > \"$lab_home/last-check.log\" 2>&1",
            "    then code=0; else code=$?; fi",
            "    if [ \"$code\" -eq \"$expect\" ]; then say \"Passed: $id\"",
            "    else say \"Not yet: $id.${hint:+ $hint}\"; status=1; fi",
            "  done",
            "done",
            "exit $status"]
    return "\n".join(out) + "\n"


def stop_sh(book, pinned) -> str:
    compose = stack_pins.lab(book.manifest)["stack"] == "compose"
    out = _prelude(book, "Stops this book's lab: " + ("its services and their data are deleted" if compose else
                                                       "the cluster is deleted") + ", and your files stay in the workspace.")
    if compose:
        out += [f"project={q(_cluster(book))}",
                "command -v docker >/dev/null 2>&1 && docker compose --project-name \"$project\" --file \"$work/compose.yaml\" "
                "down --volumes >/dev/null 2>&1 || true",
                "say \"Stopped: the services and their data are deleted.\""]
    elif pinned is not None and "k3s" in pinned.tools:
        out += [f"cluster={q(_cluster(book))}",
                "[ -x \"$bin/k3d\" ] && \"$bin/k3d\" cluster delete \"$cluster\" >/dev/null 2>&1 || true",
                "rm -f \"$lab_home/kubeconfig\"",
                "say \"Stopped: the cluster is deleted.\""]
    else:
        out += ["say \"Nothing runs beside this book's steps, so there's nothing to stop.\""]
    out += ["say \"Your files stay in $work; lab/chapter.sh starts any chapter fresh.\""]
    return "\n".join(out) + "\n"


def scripts(book) -> dict[str, str]:
    """Each script's path in the book and its text. LabError when the book's stack isn't pinned."""
    if not stack_pins.is_terminal(book.manifest):
        return {}
    which = stack_pins.lab(book.manifest)["stack"]
    pinned = stack_pins.read_pinned(book.root)
    if which != "none" and pinned is None:
        raise LabError(f"a {which} stack's local lab needs its pins: run re-check stack --pin first")
    return {"lab/start.sh": start_sh(book, pinned), "lab/chapter.sh": chapter_sh(book, pinned),
            "lab/check.sh": check_sh(book), "lab/stop.sh": stop_sh(book, pinned)}


def check(book, write: bool = False) -> tuple[list[str], list[str]]:
    """(problems, written): the scripts as generated, or with `write` written, executable."""
    try:
        wanted = scripts(book)
    except LabError as e:
        return [str(e)], []
    problems, written = [], []
    for rel, text in wanted.items():
        path = Path(book.root) / rel
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            path.chmod(0o755)
            written.append(rel)
        elif not path.exists():
            problems.append(f"{rel} is missing: run re-check lab --write")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{rel} is out of date: run re-check lab --write")
    return problems, written
