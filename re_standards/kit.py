"""The book kit: what every new draft starts with, generated, never typed (`re-check kit`).

    .gitignore                 bytecode, virtual environments and scratch never reach the draft
    examples/lib/__init__.py   threads and seeds fixed before any numerical library loads, for every example that
                               imports from lib first, here and on a reader's machine
    recordings/recorded.py     a recording writes into scratch while it runs, and is copied into the book only once
                               it finishes, with its W-48 manifest
    chapters/NN-{id}.md        with --chapter: numbered chapter stubs, in the plan's order
    narration/{id}.toml        with --chapter: each chapter's own narration file, its lexicon included, so writers
                               working in parallel never append to one shared file

The kit's settings are data/writing.toml's [kit]. `re-check style` holds a draft that started from the kit to what
can be checked of it (`style_problems`): numbered chapter files, the .gitignore, recordings through recorded.py, and
examples that neither print timings nor rely on unordered results, and import from lib first. A draft that didn't
start from it, as a member's own book doesn't, keeps the rules it had; `re-check kit` says what such a draft lacks.
"""
from __future__ import annotations

import ast
import tomllib
from pathlib import Path

from .bookfmt import split_front_matter, valid_id

MARK = "Generated by `re-check kit`"                                  # in each kit file's first lines
SEEDED = (".gitignore",)                                             # the kit's lines, and the book's own after them


def load_config(path: Path | None = None) -> dict:
    from .style import load_config as writing
    return writing(path)["kit"]


# ---------------------------------------------------------------- the files


def gitignore(cfg: dict) -> str:
    return ("# Generated by `re-check kit`: what never goes into the book. Add the book's own lines below these.\n"
            + "".join(f"{line}\n" for line in cfg["ignore"]))


LIB = '''"""Shared code for this book's examples. Generated by `re-check kit`: the book's own modules go beside this file,
in examples/lib/, never in it.

Importing anything from lib runs this file first, so an example that starts with `from lib.store import load` (or
plain `import lib`) has its threads and seeds fixed before numpy or any other numerical library loads. That's why
every example imports from lib before anything else: the same output on every run, on any machine, under load.

- Threads: each numerical library uses at most THREADS, so sums come out in the same order however busy the machine.
- Seeds: Python's `random` and numpy's global generator start from SEED. An example that draws random numbers in
  torch calls `torch.manual_seed(lib.SEED)` itself: importing torch here would slow every example that doesn't use it.
- Order: Python hashes strings differently in every run unless the runner fixes it, so a set of strings can come
  out in another order on another machine. Sort before printing.
"""
import importlib.util
import os
import random

THREADS = {threads}
SEED = {seed}

for _name in (
{variables}
):
    os.environ.setdefault(_name, str(THREADS))
os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")

random.seed(SEED)
if importlib.util.find_spec("numpy") is not None:
    import numpy

    numpy.random.seed(SEED)
'''


RECORDED = '''"""Record into scratch, then copy into the book. Generated by `re-check kit`.

A recording runs for minutes or hours: training a model, or calling one that can't run offline (W-48). While it
runs it writes into a scratch folder outside the book, so a half-made output never sits in the book's files. Only
when it finishes does it go into examples/data/recorded/NAME/, in one step, with its manifest:

    from recorded import Recording

    with Recording("teacher-labels", model="an-org/a-model", model_version="a full commit",
                   prompt_sha256=PROMPT_SHA256) as out:
        (out / "labels.jsonl").write_text(...)

Scratch is $RE_SCRATCH, else ~/scratch if it exists, else the system's temporary folder; the recording's own folder
is recordings/NAME under it. A recording that stops with an error copies nothing, and leaves its scratch folder to
read; one started again with `fresh=False` keeps what an earlier run wrote there.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

BOOK = Path(__file__).resolve().parent.parent
RECORDED = BOOK / "examples" / "data" / "recorded"
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def scratch() -> Path:
    if os.environ.get("RE_SCRATCH"):
        return Path(os.environ["RE_SCRATCH"])
    home = Path.home() / "scratch"
    return home if home.is_dir() else Path(tempfile.gettempdir())


class Recording:
    def __init__(self, name: str, *, model: str, model_version: str, prompt_sha256: str, fresh: bool = True,
                 script: str | None = None, **more):
        if not NAME.match(name):
            raise ValueError(f"{name!r}: a recording's name is lowercase words joined by hyphens")
        self.name, self.fresh = name, fresh
        caller = Path(script or sys._getframe(1).f_code.co_filename).resolve()
        try:
            script = caller.relative_to(BOOK).as_posix()
        except ValueError:
            raise ValueError(f"{caller} isn't in the book: run a recording from its script in recordings/") from None
        self.manifest = {"script": script, "model": model, "model_version": model_version,
                         "prompt_sha256": prompt_sha256, **more}
        self.folder = scratch() / "recordings" / name

    def __enter__(self) -> Path:
        if self.fresh and self.folder.exists():
            shutil.rmtree(self.folder)
        self.folder.mkdir(parents=True, exist_ok=True)
        return self.folder

    def __exit__(self, kind, error, trace) -> bool:
        if kind is not None:
            return False
        outputs = sorted(p.relative_to(self.folder).as_posix() for p in self.folder.rglob("*")
                         if p.is_file() and p.name != "manifest.json")
        if not outputs:
            raise RuntimeError(f"recording {self.name} wrote nothing into {self.folder}")
        manifest = dict(self.manifest, created=datetime.now(timezone.utc).strftime("%Y-%m-%d"), outputs=outputs)
        (self.folder / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\\n", encoding="utf-8")
        RECORDED.mkdir(parents=True, exist_ok=True)
        incoming, old = RECORDED / f".{self.name}.incoming", RECORDED / f".{self.name}.old"
        for leftover in (incoming, old):
            if leftover.exists():
                shutil.rmtree(leftover)
        shutil.copytree(self.folder, incoming)
        final = RECORDED / self.name
        if final.exists():
            final.rename(old)
        incoming.rename(final)
        if old.exists():
            shutil.rmtree(old)
        print(f"recorded {self.name}: {len(outputs)} file(s) into {final.relative_to(BOOK).as_posix()}")
        return False
'''


def files(cfg: dict | None = None) -> dict[str, str]:
    """Every kit file, by its path in the book."""
    cfg = cfg or load_config()
    variables = "\n".join(f'    "{v}",' for v in cfg["thread_variables"])
    return {".gitignore": gitignore(cfg),
            "examples/lib/__init__.py": LIB.format(threads=int(cfg["threads"]), seed=int(cfg["seed"]), variables=variables),
            "recordings/recorded.py": RECORDED}


def chapter_stub(chapter_id: str) -> str:
    words = chapter_id.replace("-", " ")
    return f"---\nchapter_id: {chapter_id}\n---\n\n# {words[:1].upper() + words[1:]}\n"


NARRATION_STUB = '''# Chapter {chapter_id}'s narration (re-check narration): descriptions of its examples, blocks and tables, as
# [examples.ID], [[blocks]] and [[tables]], and its own readings. Only this chapter's writer edits this file, so
# writers working in parallel never append to one shared lexicon. A reading every chapter needs goes into
# narration/lexicon.toml, which wins over a chapter's.

[terms]

[words]
'''


# ---------------------------------------------------------------- `re-check kit`


def is_draft(root: Path) -> bool:
    manifest = root / "book.toml"
    if not manifest.is_file():
        return True
    try:
        return tomllib.loads(manifest.read_text(encoding="utf-8")).get("status", "draft") == "draft"
    except tomllib.TOMLDecodeError:
        return True


def missing_ignores(text: str, cfg: dict) -> list[str]:
    have = {line.strip() for line in text.splitlines()}
    return [line for line in cfg["ignore"] if line not in have]


def check(root: Path, cfg: dict | None = None) -> list[str]:
    """What the book lacks of the kit: a file missing, a generated one changed, or kit lines missing from .gitignore."""
    cfg = cfg or load_config()
    problems = []
    for rel, text in files(cfg).items():
        path = root / rel
        if not path.is_file():
            problems.append(f"{rel} is missing: re-check kit --book . --write")
        elif rel in SEEDED:
            lacks = missing_ignores(path.read_text(encoding="utf-8"), cfg)
            if lacks:
                problems.append(f"{rel} doesn't ignore {', '.join(lacks)}: re-check kit --book . --write adds them")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(own_file(rel) if not ours(path) else
                            f"{rel} isn't the kit's: it's generated, so the book's own code goes beside it; "
                            "re-check kit --book . --write writes it again")
    return problems


def ours(path: Path) -> bool:
    """Whether a file is one the kit wrote, an earlier kit's included, rather than the book's own."""
    return MARK in path.read_text(encoding="utf-8", errors="replace")[:400]


def own_file(rel: str) -> str:
    return (f"{rel} is the book's own, not the kit's: move its code into a module beside it, delete it, and run "
            "re-check kit --book . --write")


def existing_chapters(root: Path) -> dict[str, str]:
    """chapter_id -> its file, for the chapters already in the book."""
    out = {}
    for path in sorted((root / "chapters").glob("*.md")) if (root / "chapters").is_dir() else []:
        try:
            front = split_front_matter(path.read_text(encoding="utf-8"))[0]
        except Exception:                   # a chapter that doesn't parse is the section-ID check's to report
            front = {}
        cid = str(front.get("chapter_id") or "")
        out[cid or path.stem] = path.relative_to(root).as_posix()
    return out


def write(root: Path, chapters: list[str] | None = None, cfg: dict | None = None) -> tuple[list[str], list[str]]:
    """The kit into the book: (what was written, problems). A generated file is written again; .gitignore gains the
    kit's missing lines and keeps the book's own; a chapter that exists, or its narration file, is never touched."""
    cfg = cfg or load_config()
    written, problems = [], []
    for rel, text in files(cfg).items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if rel in SEEDED and path.is_file():
            current = path.read_text(encoding="utf-8")
            lacks = missing_ignores(current, cfg)
            if lacks:
                path.write_text(current.rstrip("\n") + "\n" + "".join(f"{line}\n" for line in lacks), encoding="utf-8")
                written.append(rel)
        elif path.is_file() and not ours(path):
            problems.append(own_file(rel))           # never overwritten: it may hold the book's code
        elif not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(rel)
    have = existing_chapters(root)
    for n, cid in enumerate(chapters or [], 1):
        if not valid_id(cid):
            problems.append(f"--chapter {cid!r}: a chapter ID is lowercase words joined by hyphens")
            continue
        rel = f"chapters/{n:02d}-{cid}.md"
        if cid in have:
            if have[cid] != rel:
                problems.append(f"{have[cid]} holds chapter {cid}, which the plan puts {n}: rename it to {rel}")
        elif (root / rel).exists() or any(f.startswith(f"chapters/{n:02d}-") for f in have.values()):
            problems.append(f"{rel}: another chapter is numbered {n:02d}: pass every chapter in the plan's order")
            continue
        else:
            (root / "chapters").mkdir(exist_ok=True)
            (root / rel).write_text(chapter_stub(cid), encoding="utf-8")
            written.append(rel)
        narration = root / "narration" / f"{cid}.toml"
        if not narration.exists():
            narration.parent.mkdir(exist_ok=True)
            narration.write_text(NARRATION_STUB.format(chapter_id=cid), encoding="utf-8")
            written.append(narration.relative_to(root).as_posix())
    return written, problems


# ---------------------------------------------------------------- what `re-check style` holds a draft to


def chapter_files(book) -> list[str]:
    """kit: chapter files named chapters/NN-{chapter_id}.md, numbered from 01 in reading order with no gaps."""
    problems = []
    for n, c in enumerate(book.chapters, 1):
        want = f"chapters/{n:02d}-{c.chapter_id}.md"
        if c.file != want:
            problems.append(f"{c.file}: kit: name chapter files chapters/NN-{{chapter_id}}.md, numbered from 01 in the "
                            f"plan's order with no gaps, since file names set the reading order; this one reads as "
                            f"chapter {n}, so {want}, or the number the plan gives it")
    return problems


def ignores_problems(root: Path) -> list[str]:
    path = root / ".gitignore"
    lines = [line.strip() for line in path.read_text(encoding="utf-8").splitlines()] if path.is_file() else []
    if any("__pycache__" in line and not line.startswith("#") for line in lines) and \
            any("scratch" in line and not line.startswith("#") for line in lines):
        return []
    return [".gitignore: kit: ignore __pycache__/ and scratch/, so bytecode and scratch files never reach the draft: "
            "re-check kit --book . --write"]


def recordings_problems(root: Path) -> list[str]:
    """kit: a recording that writes into examples/data/recorded itself, rather than through recorded.py."""
    problems = []
    folder = root / "recordings"
    for path in sorted(folder.glob("*.py")) if folder.is_dir() else []:
        if path.name == "recorded.py":
            continue
        rel = path.relative_to(root).as_posix()
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        imports = {a.name.split(".")[0] for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
        imports |= {(n.module or "").split(".")[0] for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)}
        names = [n for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)
                 and ("data/recorded" in n.value or n.value == "recorded")]
        if names and "recorded" not in imports:
            problems.append(f"{rel}:{names[0].lineno}: kit: a recording writes into scratch while it runs, and into "
                            "examples/data/recorded only when it finishes: use `with Recording(...) as out:` from "
                            "recordings/recorded.py")
    return problems


def has_kit(root: Path) -> bool:
    """Whether the book started from the kit: its .gitignore or examples/lib says so."""
    return any((root / rel).is_file() and ours(root / rel) for rel in (".gitignore", "examples/lib/__init__.py"))


def style_problems(book, cfg: dict | None = None) -> list[str]:
    """What `re-check style` holds a draft to, once it holds the kit."""
    if not has_kit(book.root):
        return []
    cfg = cfg or load_config()
    return (chapter_files(book) + ignores_problems(book.root) + lint_examples(book.root, cfg)
            + recordings_problems(book.root))


# ---------------------------------------------------------------- W-17: examples that give the same output every time

SORTING = {"sorted", "len", "set", "frozenset", "min", "max", "any", "all", "sum"}   # don't care about order
SEQUENCING = {"list", "tuple", "enumerate", "zip", "map", "filter", "print", "str", "repr", "next", "iter"}
SET_METHODS = {"union", "intersection", "difference", "symmetric_difference", "copy"}


class _Names:
    """What each name means after the module's imports: `import time as t` makes t time; `from datetime import
    datetime` makes datetime datetime.datetime."""

    def __init__(self, tree: ast.AST):
        self.alias: dict[str, str] = {}
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                for a in n.names:
                    self.alias[(a.asname or a.name).split(".")[0]] = a.name if a.asname else a.name.split(".")[0]
            elif isinstance(n, ast.ImportFrom) and n.module and not n.level:
                for a in n.names:
                    self.alias[a.asname or a.name] = f"{n.module}.{a.name}"

    def dotted(self, node: ast.AST) -> str | None:
        """`np.random.seed` as numpy.random.seed; None for anything that doesn't start from an imported name."""
        parts = []
        while isinstance(node, ast.Attribute):
            parts.append(node.attr)
            node = node.value
        if not isinstance(node, ast.Name):
            return None
        head = self.alias.get(node.id)
        return ".".join([head, *reversed(parts)]) if head else None


def _covers(name: str | None, refused: list[str]) -> bool:
    """Whether a dotted name is refused: an entry that's a module covers everything in it."""
    return bool(name) and any(name == r or name.startswith(r + ".") for r in refused)


class _Lint:
    """One file's W-17 problems: the clock or memory read, and unordered results whose order shows."""

    def __init__(self, rel: str, tree: ast.AST, cfg: dict):
        self.rel, self.tree, self.cfg = rel, tree, cfg
        self.names = _Names(tree)
        self.up = {child: parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)}
        self.problems: set[tuple[int, str]] = set()
        self.set_names = self._set_names()

    def say(self, node: ast.AST, text: str) -> None:
        self.problems.add((node.lineno, f"{self.rel}:{node.lineno}: W-17: {text}"))

    # -- what's a set

    def _set_names(self) -> set[str]:
        """Names only ever bound to a set, by a simple assignment."""
        bound: dict[str, bool] = {}
        for n in ast.walk(self.tree):
            if isinstance(n, ast.AnnAssign) and n.value is not None:
                targets, value = [n.target], n.value
            elif isinstance(n, ast.Assign):
                targets, value = n.targets, n.value
            else:
                continue
            for t in targets:
                if isinstance(t, ast.Name):
                    bound[t.id] = bound.get(t.id, True) and self._is_set(value, set())
        return {k for k, v in bound.items() if v}

    def _is_set(self, node: ast.AST, names: set[str]) -> bool:
        if isinstance(node, (ast.Set, ast.SetComp)):
            return True
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in ("set", "frozenset"):
            return True
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr in SET_METHODS:
            return self._is_set(node.func.value, names)
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.BitOr, ast.BitAnd, ast.Sub, ast.BitXor)):
            return self._is_set(node.left, names) or self._is_set(node.right, names)
        return isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load) and node.id in names

    # -- where a value's order shows

    def consumer(self, node: ast.AST) -> tuple[ast.AST | None, bool]:
        """What takes this value, and whether it iterates it, looking through generators: a generator inside sorted()
        is sorted."""
        parent = self.up.get(node)
        if isinstance(parent, ast.comprehension) and parent.iter is node:
            comp = self.up.get(parent)
            return self.consumer(comp) if isinstance(comp, ast.GeneratorExp) else (comp, True)
        if isinstance(parent, (ast.For, ast.AsyncFor)) and parent.iter is node:
            return parent, True
        return parent, False

    def shows_order(self, node: ast.AST) -> bool:
        """Iterated into a list or a loop, printed, joined, listed or formatted, where its order reaches the output.
        sorted(), len(), set(), min(), max() and `in` don't care about order."""
        c, iterated = self.consumer(node)
        if iterated:
            return isinstance(c, (ast.For, ast.AsyncFor, ast.ListComp))
        if isinstance(c, ast.Call):
            f = c.func
            return (isinstance(f, ast.Name) and f.id in SEQUENCING) or \
                (isinstance(f, ast.Attribute) and f.attr in ("join", "extend", "writelines"))
        return isinstance(c, (ast.FormattedValue, ast.Starred))

    def assigned_to(self, node: ast.AST) -> str | None:
        parent = self.up.get(node)
        if isinstance(parent, ast.Assign) and len(parent.targets) == 1 and isinstance(parent.targets[0], ast.Name):
            return parent.targets[0].id
        return None

    def order_shows(self, node: ast.AST) -> bool:
        """The value's order shows where it's used, or wherever the name it's assigned to is used."""
        target = self.assigned_to(node)
        if target is None:
            return self.shows_order(node)
        return any(self.shows_order(n) for n in ast.walk(self.tree)
                   if isinstance(n, ast.Name) and n.id == target and isinstance(n.ctx, ast.Load))

    # -- the rules

    def run(self) -> list[str]:
        timing, unordered, methods = self.cfg["timing"], self.cfg["unordered"], set(self.cfg["unordered_methods"])
        for n in ast.walk(self.tree):
            if isinstance(n, (ast.Attribute, ast.Name)) and not isinstance(self.up.get(n), ast.Attribute):
                name = self.names.dotted(n)
                if _covers(name, timing):
                    self.say(n, f"{name} reads the clock or the memory in use, so what an example prints with it "
                                "changes from run to run and under load: print only what the inputs decide, and leave "
                                "speed to the prose or a recording")
            if not isinstance(n, ast.Call):
                continue
            name = self.names.dotted(n.func)
            method = n.func.attr if isinstance(n.func, ast.Attribute) else None
            listing = _covers(name, unordered) or (name is None and method in methods)
            if listing and self.order_shows(n):
                self.say(n, f"{name or '.' + method + '()'} gives its results in whatever order the file system or the "
                            "workers do, which differs between machines: wrap it in sorted()")
            if method == "pop" and not n.args and self._is_set(n.func.value, self.set_names):
                self.say(n, "set.pop() takes whichever item the set holds first, which can differ between runs: take "
                            "min() or max(), or sort it first")
        for n in ast.walk(self.tree):
            is_set = (isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load) and n.id in self.set_names) or \
                (not isinstance(n, ast.Name) and self._is_set(n, self.set_names))
            if is_set and self.shows_order(n):
                self.say(n, "a set's order can differ between runs: wrap it in sorted() before iterating, printing or "
                            "joining it")
        return [text for _, text in sorted(self.problems)]


def import_order(rel: str, tree: ast.Module, cfg: dict) -> list[str]:
    """An example imports from lib before any numerical library, so lib fixes threads and seeds first."""
    numerical = set(cfg["numerical"])
    statements = []
    for node in tree.body:
        if isinstance(node, ast.Try):
            statements += node.body
        elif isinstance(node, ast.If):
            statements += node.body
        else:
            statements.append(node)
    for node in statements:
        if isinstance(node, ast.Import):
            tops = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom) and not node.level:
            tops = [(node.module or "").split(".")[0]]
        else:
            continue
        if "lib" in tops:
            return []
        heavy = [t for t in tops if t in numerical]
        if heavy:
            return [f"{rel}:{node.lineno}: W-17: import from lib first (`import lib`, or `from lib.x import y`), so "
                    f"threads and seeds are fixed before {heavy[0]} loads"]
    return []


def lint_examples(root: Path, cfg: dict | None = None) -> list[str]:
    """W-17 by the code: every .py under examples/ but its data, and each example's imports."""
    cfg = cfg or load_config()
    folder = root / "examples"
    problems = []
    for path in sorted(folder.rglob("*.py")) if folder.is_dir() else []:
        rel = path.relative_to(root).as_posix()
        parts = path.relative_to(folder).parts
        if parts[0] == "data" or any(p.startswith(".") or p in ("__pycache__", ".venv") for p in parts):
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue                           # the examples' own run reports a file that doesn't parse
        problems += _Lint(rel, tree, cfg).run()
        if len(parts) == 1:
            problems += import_order(rel, tree, cfg)
    return problems
